const COLUMN_VALUES = new Set<string>(Object.values(Column));
const COLUMN_BY_LEGACY_NAME: Record<keyof typeof LegacyColumn, Column> = Column;

export function parseSavedColumn(value: unknown): Column | null {
  if (typeof value === 'string') {
    return COLUMN_VALUES.has(value) ? (value as Column) : null;
  }
  if (typeof value === 'number') {
    const name = LegacyColumn[value] as keyof typeof LegacyColumn | undefined;
    return name === undefined ? null : COLUMN_BY_LEGACY_NAME[name];
  }
  return null;
}

export function parseSavedColumns(
  columns: { column: unknown }[],
): SelectedColumn[] {
  return columns.flatMap(({ column }) => {
    const parsed = parseSavedColumn(column);
    return parsed === null ? [] : [{ column: parsed }];
  });
}
